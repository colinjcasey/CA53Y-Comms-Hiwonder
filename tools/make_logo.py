#!/usr/bin/env python3
"""
Turn your own logo into the boot splash for CA53Y Comms (Hiwonder board).

    pip install pillow
    python tools/make_logo.py my_logo.png

Writes CA53Y_Hiwonder/logo.h. The firmware picks it up automatically on the next build;
delete logo.h to go back to the built-in sunburst. Transparent areas become the dark lacquer background.

Options:
    --size 150        largest width/height in pixels (max 170; the logo area is 320x176)
    --bg 0F2A30       background color for transparent areas (hex)
"""
import argparse
import os
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Needs Pillow: pip install pillow")

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("image")
ap.add_argument("--size", type=int, default=150)
ap.add_argument("--bg", default="0F2A30")
ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "CA53Y_Hiwonder", "logo.h"))
a = ap.parse_args()

size = max(16, min(a.size, 170))
bg = tuple(int(a.bg[i:i + 2], 16) for i in (0, 2, 4))
im = Image.open(a.image).convert("RGBA")
im.thumbnail((size, size), Image.LANCZOS)
flat = Image.new("RGBA", im.size, bg + (255,))
flat.alpha_composite(im)
flat = flat.convert("RGB")
w, h = flat.size

words = []
raw = flat.tobytes()
for i in range(0, len(raw), 3):
    r, g, b = raw[i], raw[i + 1], raw[i + 2]
    c = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    words.append(((c & 0xFF) << 8) | (c >> 8))   # byte-swapped RGB565, what the panel wants

with open(a.out, "w") as f:
    f.write("// Generated by tools/make_logo.py from %s. Delete this file to use the built-in sunburst.\n" % os.path.basename(a.image))
    f.write("#pragma once\n#define CA53Y_LOGO_W %d\n#define CA53Y_LOGO_H %d\n" % (w, h))
    f.write("static const uint16_t ca53y_logo[%d] PROGMEM = {\n" % len(words))
    for i in range(0, len(words), 16):
        f.write("  " + ", ".join("0x%04X" % x for x in words[i:i + 16]) + ",\n")
    f.write("};\n")
print("Wrote %s (%dx%d, %d KB of flash)" % (os.path.normpath(a.out), w, h, len(words) * 2 // 1024))
